#!/usr/bin/env python3
"""Export the document-type vocabulary and the stop words for the phone's on-device index.

    python3 scripts/export_document_types.py          # rewrite the file
    python3 scripts/export_document_types.py --check  # exit 1 if it is out of date

The phone classifies and tokenises with the SAME rules as the server (document_type.py and
lexical.py). This writes them as a small text file that the Android app ships as an asset.
A test fails if the checked-in copy drifts from the Python source.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api/src"))
TARGET = ROOT / "apps/web/android-plugin/document_types.tsv"


def render() -> str:
    from memora.services.document_type import VOCABULARY
    from memora.services.lexical import STOP

    lines = ["# Generated by scripts/export_document_types.py. Do not edit by hand."]
    lines += [f"T\t{label}\t" + "|".join(aliases) for label, aliases in VOCABULARY.items()]
    lines += [f"S\t{word}" for word in sorted(STOP)]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        return 0 if TARGET.exists() and TARGET.read_text(encoding="utf-8") == text else 1
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
