#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE ROLE memora_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT CONNECT ON DATABASE memora TO memora_app;
GRANT USAGE ON SCHEMA public TO memora_app;
ALTER DEFAULT PRIVILEGES FOR ROLE memora IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO memora_app;
ALTER DEFAULT PRIVILEGES FOR ROLE memora IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO memora_app;
SQL
