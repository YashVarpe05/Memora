"""Identifier masking.

A false positive is worse than a miss: masking a receipt ID or a roll number silently
destroys retrievable text, and nobody notices until a search fails. So most of these
tests are about what must be left alone.

No real Aadhaar or PAN appears here. Valid test numbers are generated by computing the
Verhoeff check digit over an arbitrary prefix.
"""

import pytest

from memora.services.embedding import require_masked
from memora.services.masking import (
    _D,
    _P,
    AADHAAR_TOKEN,
    PAN_TOKEN,
    MaskedText,
    contains_identifier,
    mask_identifiers,
    verhoeff_valid,
)

_INV = (0, 4, 3, 2, 1, 5, 6, 7, 8, 9)


def aadhaar(prefix11: str) -> str:
    """Append the correct Verhoeff check digit, producing a structurally valid number."""
    assert len(prefix11) == 11
    checksum = 0
    for i, digit in enumerate(reversed(prefix11)):
        checksum = _D[checksum][_P[(i + 1) % 8][int(digit)]]
    return prefix11 + str(_INV[checksum])


# --- what must be masked ------------------------------------------------------


def test_valid_aadhaar_is_masked():
    number = aadhaar("23456789012")
    masked = mask_identifiers(f"Aadhaar No. {number} issued 2019")

    assert number not in masked.value
    assert AADHAAR_TOKEN in masked.value
    assert masked.was_masked


@pytest.mark.parametrize("sep", ["", " ", "-"])
def test_grouped_aadhaar_formats_are_masked(sep):
    number = aadhaar("23456789012")
    grouped = sep.join([number[:4], number[4:8], number[8:]])

    masked = mask_identifiers(f"UID {grouped}")

    assert AADHAAR_TOKEN in masked.value
    assert number[8:] not in masked.value


def test_pan_is_masked():
    masked = mask_identifiers("PAN: ABCDE1234F on file")

    assert "ABCDE1234F" not in masked.value
    assert PAN_TOKEN in masked.value


def test_multiple_identifiers_in_one_document():
    number = aadhaar("34567890123")
    masked = mask_identifiers(f"Aadhaar {number} and PAN ZYXWV9876Q")

    assert masked.value.count(AADHAAR_TOKEN) == 1
    assert masked.value.count(PAN_TOKEN) == 1
    assert len(masked.detections) == 2


# --- what must be left alone --------------------------------------------------


def test_twelve_digits_failing_verhoeff_are_untouched():
    """A receipt ID is twelve digits too. Masking it destroys a findable document."""
    number = aadhaar("23456789012")
    broken = number[:-1] + str((int(number[-1]) + 1) % 10)
    assert not verhoeff_valid(broken)

    masked = mask_identifiers(f"Receipt {broken}")

    assert broken in masked.value
    assert not masked.was_masked


def test_numbers_starting_with_zero_or_one_are_untouched():
    """UIDAI never issues an Aadhaar beginning 0 or 1, so these are something else."""
    for prefix in ("0", "1"):
        candidate = prefix + aadhaar("23456789012")[1:]
        assert mask_identifiers(f"ref {candidate}").value.count(AADHAAR_TOKEN) == 0


def test_phone_numbers_are_untouched():
    masked = mask_identifiers("call me on 919876543210 or 9876543210")
    assert not masked.was_masked


def test_roll_number_is_untouched():
    masked = mask_identifiers("Roll No. B190123456 semester VII")
    assert not masked.was_masked


def test_eleven_and_thirteen_digit_runs_are_untouched():
    for digits in ("2345678901", "23456789012345"):
        assert not mask_identifiers(f"id {digits}").was_masked


def test_match_inside_a_longer_digit_run_is_untouched():
    number = aadhaar("23456789012")
    masked = mask_identifiers(f"txn 99{number}99")
    assert not masked.was_masked


def test_lowercase_pan_shape_is_untouched():
    masked = mask_identifiers("code abcde1234f")
    assert not masked.was_masked


def test_wrong_pan_shape_is_untouched():
    for candidate in ("ABCD1234F", "ABCDE12345", "ABCDE1234", "ABCDEF1234F"):
        assert not mask_identifiers(f"ref {candidate}").was_masked


def test_clean_text_passes_through_unchanged():
    text = "Third normal form eliminates transitive dependency on the primary key."
    masked = mask_identifiers(text)

    assert masked.value == text
    assert masked.detections == ()
    assert not masked.was_masked


# --- properties ---------------------------------------------------------------


def test_masking_is_idempotent():
    number = aadhaar("45678901234")
    once = mask_identifiers(f"Aadhaar {number}")
    twice = mask_identifiers(once.value)

    assert once.value == twice.value
    assert not twice.was_masked


def test_detection_never_carries_the_value():
    """Detections get logged. The matched digits must not be reachable from one."""
    number = aadhaar("23456789012")
    detection = mask_identifiers(f"Aadhaar {number}").detections[0]

    assert detection.kind == "aadhaar"
    assert number not in repr(detection)
    assert not any(isinstance(v, str) and v.isdigit() for v in vars(detection).values())


# --- the guarantee ------------------------------------------------------------


def test_masked_text_cannot_be_constructed_directly():
    """If this ever passes construction, the whole rule becomes advisory."""
    with pytest.raises(TypeError, match="cannot be constructed directly"):
        MaskedText(object(), "1234 5678 9012", ())


def test_embedder_refuses_a_plain_string():
    """The point of the design: there is no call ordering that embeds raw text.

    Written as an attempt to break the rule. If it ever stops raising, unmasked
    document text can reach a hosted API and the PRODUCT.md claim is false.
    """
    with pytest.raises(TypeError, match="requires MaskedText"):
        require_masked(["Aadhaar 2345 6789 0123"])  # type: ignore[list-item]


def test_embedder_accepts_masked_text():
    payload = require_masked([mask_identifiers("hello")])
    assert payload == ["hello"]


def test_gmail_thread_id_is_untouched():
    """Regression: a real mail.pdf carried a Gmail thread id whose middle twelve digits
    happen to pass Verhoeff. Masking it would break the URL and make the email harder to
    find - which is the failure mode this whole design is arranged around.
    """
    url = "?ik=1&view=pt&search=all&permthid=thread-a:r8812345678900512345&simpl=msg-a:r99"
    masked = mask_identifiers(url)

    assert masked.value == url
    assert not masked.was_masked


# --- adversarial: forging a MaskedText ----------------------------------------
#
# The token guards provenance, and an adversarial probe found four ways past it:
# object.__new__, dataclasses.replace, subclassing, and importing the token. Every one
# routes around __init__, which no construction-time check can prevent in a language
# with object.__new__.
#
# So the guarantee is content, verified at construction AND at the embedder. Forging a
# MaskedText is still possible; forging one that carries an identifier past the embedder
# is not. These tests are the record of that, and an examiner may well try them live.

RAW = "Aadhaar 234567890124 here"


def forged_via_object_new() -> MaskedText:
    """Skips __init__ entirely. Nothing at construction time can stop this."""
    obj = object.__new__(MaskedText)
    for name, value in (("_key", None), ("value", RAW), ("detections", ())):
        object.__setattr__(obj, name, value)
    return obj


def test_object_new_forgery_is_stopped_at_the_embedder():
    with pytest.raises(ValueError, match="unmasked identifier"):
        require_masked([forged_via_object_new()])


def test_dataclasses_replace_cannot_inject_raw_text():
    """The likeliest accident: replace() reuses the real token from a valid instance."""
    import dataclasses

    with pytest.raises(ValueError, match="unmasked identifier"):
        dataclasses.replace(mask_identifiers("clean"), value=RAW)


def test_masked_text_cannot_be_subclassed():
    with pytest.raises(TypeError, match="final"):

        class Forged(MaskedText):
            pass


def test_importing_the_private_token_does_not_help():
    """Provenance is forgeable. Content is not."""
    from memora.services import masking

    with pytest.raises(ValueError, match="unmasked identifier"):
        MaskedText(masking._MINT, RAW, ())


def test_pickle_roundtrip_of_a_forgery_is_still_stopped():
    import pickle

    revived = pickle.loads(pickle.dumps(forged_via_object_new()))

    with pytest.raises(ValueError, match="unmasked identifier"):
        require_masked([revived])


def test_deepcopy_of_a_legitimate_instance_stays_valid():
    """Copying masked text is not an attack, and must keep working."""
    import copy

    original = mask_identifiers("clean text")
    assert require_masked([copy.deepcopy(original)]) == ["clean text"]


def test_pickle_roundtrip_of_a_legitimate_instance_stays_valid():
    import pickle

    original = mask_identifiers("clean text")
    assert require_masked([pickle.loads(pickle.dumps(original))]) == ["clean text"]


def test_a_forgery_carrying_no_identifier_is_harmless():
    """The check is about content, not ceremony. Clean text is clean however it arrived."""
    obj = object.__new__(MaskedText)
    for name, value in (("_key", None), ("value", "nothing sensitive"), ("detections", ())):
        object.__setattr__(obj, name, value)

    assert require_masked([obj]) == ["nothing sensitive"]


def test_the_sixteen_digit_virtual_id_is_masked_like_the_number():
    cases = {
        "VID : 2345 6789 0123 4508 printed": "VID : [AADHAAR_VID] printed",
        "vid 2345678901234508 glued": "vid [AADHAAR_VID] glued",
        "dashed 2345-6789-0123-4508": "dashed [AADHAAR_VID]",
        "bad 2345678901234509 keep": "bad 2345678901234509 keep",
        "both 2345678901234508 and 234567890124 and ABCDE1234F": (
            "both [AADHAAR_VID] and [AADHAAR_NUMBER] and [PAN_NUMBER]"
        ),
    }
    for text, expected in cases.items():
        assert mask_identifiers(text).value == expected
    assert contains_identifier("VID 2345678901234508")
